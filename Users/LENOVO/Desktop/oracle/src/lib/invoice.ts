import type { InvoiceItem } from '@/types';

// ─── Types ─────────────────────────────

export interface InvoiceData {
  agencyName: string;
  agencyAddress: string;
  agencyGST?: string;
  agencyPhone: string;
  agencyEmail: string;
  clientName: string;
  clientAddress?: string;
  clientGST?: string;
  items: InvoiceItem[];
  invoiceNumber: string;
  invoiceDate: string;
  dueDate: string;
  paymentTerms: string;
  notes?: string;
  upiId?: string;
  bankDetails?: string;
}

// ─── Generate Invoice Number ───────────

export function generateInvoiceNumber(prefix: string = 'INV'): string {
  if (typeof window === 'undefined') return `${prefix}-2026-001`;
  try {
    const year = new Date().getFullYear();
    const raw = localStorage.getItem('oracle_invoice_counter');
    const counter = raw ? parseInt(raw, 10) + 1 : 1;
    localStorage.setItem('oracle_invoice_counter', String(counter));
    return `${prefix}-${year}-${String(counter).padStart(3, '0')}`;
  } catch (e) {
    console.warn('[Invoice] Failed to read invoice counter from localStorage:', e);
    return `${prefix}-${new Date().getFullYear()}-001`;
  }
}

// ─── Calculate Invoice Totals ──────────

export function calculateInvoiceTotals(items: InvoiceItem[]) {
  const subtotal = items.reduce((sum, item) => sum + item.amount, 0);
  const gst = subtotal * 0.18;
  const total = subtotal + gst;
  return { subtotal, gst, total };
}

