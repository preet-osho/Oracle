// ─── Generate PDF via html2canvas + jsPDF ──

export async function generateInvoicePDF(data: InvoiceData): Promise<Blob | null> {
  try {
    const [{ default: jsPDF }, html2canvasModule] = await Promise.all([
      import('jspdf'),
      import('html2canvas'),
    ]);

    const html2canvas = html2canvasModule.default;
    const html = buildInvoiceHTML(data);

    // Create off-screen container
    const container = document.createElement('div');
    container.innerHTML = html;
    container.style.cssText = 'position:fixed;left:-9999px;top:0;width:800px;background:#fff';
    document.body.appendChild(container);

    const canvas = await html2canvas(container, {
      scale: 2,
      useCORS: true,
      backgroundColor: '#ffffff',
      width: 800,
    });

    document.body.removeChild(container);

    const imgData = canvas.toDataURL('image/png');
    const pdf = new jsPDF('p', 'mm', 'a4');
    const pdfWidth = pdf.internal.pageSize.getWidth();
    const pdfHeight = (canvas.height * pdfWidth) / canvas.width;

    pdf.addImage(imgData, 'PNG', 0, 0, pdfWidth, pdfHeight);

    return pdf.output('blob');
  } catch (e) {
    console.warn('[Invoice] Failed to generate PDF:', e);
    return null;
  }
}

// ─── Trigger Download ──────────────────

export async function downloadInvoicePDF(data: InvoiceData, filename?: string): Promise<void> {
  const blob = await generateInvoicePDF(data);
  if (!blob) return;

  const name = filename || `invoice-${data.invoiceNumber.toLowerCase()}.pdf`;
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = name;
  a.click();
  URL.revokeObjectURL(url);
}

// ─── Format Invoice as Text ────────────

export function formatInvoiceAsText(data: InvoiceData): string {
  const { subtotal, gst, total } = calculateInvoiceTotals(data.items);

  let text = `INVOICE ${data.invoiceNumber}\n`;
  text += `Date: ${data.invoiceDate} | Due: ${data.dueDate}\n\n`;
  text += `FROM: ${data.agencyName}\n${data.agencyAddress}\n`;
  if (data.agencyGST) text += `GSTIN: ${data.agencyGST}\n`;
  text += `${data.agencyPhone} | ${data.agencyEmail}\n\n`;
  text += `TO: ${data.clientName}\n`;
  if (data.clientAddress) text += `${data.clientAddress}\n`;
  if (data.clientGST) text += `GSTIN: ${data.clientGST}\n`;
  text += `\n${'─'.repeat(50)}\n`;
  text += `Description`.padEnd(30) + `Qty`.padStart(5) + `Rate`.padStart(12) + `Amount`.padStart(12) + `\n`;
  text += `${'─'.repeat(50)}\n`;

  for (const item of data.items) {
    text += item.description.padEnd(30) +
      String(item.quantity).padStart(5) +
      `₹${item.rate.toLocaleString('en-IN')}`.padStart(12) +
      `₹${item.amount.toLocaleString('en-IN')}`.padStart(12) + `\n`;
  }

  text += `${'─'.repeat(50)}\n`;
  text += `Subtotal`.padEnd(47) + `₹${subtotal.toLocaleString('en-IN')}`.padStart(12) + `\n`;
  text += `GST (18%)`.padEnd(47) + `₹${gst.toLocaleString('en-IN')}`.padStart(12) + `\n`;
  text += `TOTAL`.padEnd(47) + `₹${total.toLocaleString('en-IN')}`.padStart(12) + `\n\n`;

  if (data.upiId) text += `UPI ID: ${data.upiId}\n`;
  if (data.bankDetails) text += `${data.bankDetails}\n`;
  text += `Payment Terms: ${data.paymentTerms}\n`;
  if (data.notes) text += `\nNotes: ${data.notes}\n`;
  text += `\nThank you for your business!`;

  return text;
}
